  modelShare: () => ipcRenderer.invoke('privacy:modelShare'),
  fixApply: (request) => ipcRenderer.invoke('fix:apply', request),
  fixList: () => ipcRenderer.invoke('fix:list'),
  fixUndo: (ids) => ipcRenderer.invoke('fix:undo', ids),
  fixLogCheck: () => ipcRenderer.invoke('fix:verify'),
  fixOpenLog: () => ipcRenderer.invoke('fix:openLog'),
